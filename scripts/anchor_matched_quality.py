"""Match segment-quality training to the modern owners and dense candidate graph.

All training evidence is generated by models that exclude that training match.
This trains a full four-match quality head, so the four matches are NOT its
held-out evaluation. WPY selects a small blend; WQQ inference cannot read truth.
"""
from __future__ import annotations
import argparse, json, os, pickle, sys, time
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT/'private/improvement/runtime'), str(ROOT)]
os.environ.setdefault('OMP_NUM_THREADS', '2')
os.environ.setdefault('OPENBLAS_NUM_THREADS', '2')
import numpy as np
from scipy.special import expit, logit
from sklearn.ensemble import HistGradientBoostingRegressor
from threadpoolctl import threadpool_limits
from second_zero.common import sha256
from second_zero.evaluate import official_metrics
from scripts import sprint_decoder_segments_geometry_v2 as graph
from scripts import sprint_decoder_lattice as lattice

TRAIN = ['J03WMX', 'J03WN1', 'J03WOH', 'J03WOY']
READS = set()
HASHES = {}

def guard(event, args):
    if event == 'open' and isinstance(args[0], (str, bytes, os.PathLike)):
        p = os.fsdecode(args[0])
        if 'J03WR9' in p or '/evaluation/gt/' in p:
            raise PermissionError('No public or reserved assets')
        if p.endswith('.truth.npy'):
            if not any(Path(p).name.startswith(m+'-') for m in TRAIN+['J03WPY']):
                raise PermissionError('WQQ truth forbidden during model construction')
            READS.add(p)

def write(p, value):
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open('x') as f: json.dump(value, f, indent=2)

def array(folder, key, field='logit'):
    p = ROOT/folder/(key+'.npz'); HASHES[str(p.relative_to(ROOT))] = sha256(p)
    with np.load(p) as a: return a[field].copy()

def evidence(key):
    x = graph.signals(key)
    x[:, 0] = array('runs/two-hour-sprint/carrier-mixture-v1', key)
    base = array('runs/two-hour-sprint/status-mixture-v1/reliability', key, 'predicted')
    return x, base

def pool(x, base):
    return lattice.proposals(x[:, 0], base, graph.proposals(x[:, 0], base, x[:, 4], x[:, 7:10]), 16)

def fit(out):
    started = time.monotonic(); xx=[]; yy=[]; counts={}
    params = dict(max_iter=180, max_leaf_nodes=15, max_depth=5, min_samples_leaf=40,
                  learning_rate=.05, l2_regularization=5., random_state=20261024, early_stopping=False)
    write(out/'protocol.json', {
        'training_matches': TRAIN, 'calibration_match':'J03WPY', 'evaluation_match':'J03WQQ',
        'hypothesis':'Old quality head sees old owners and sparse proposals. Train identical features/objective on modern OOF owners and actual dense lattice.',
        'primary_training_owners':['opposite-fold learned-fill', 'half probability mixture of opposite-fold learned-fill and long TCN'],
        'status':'opposite-fold status-crossfit-v2/cost50',
        'geometry':'same opposite-fold learned imputer as each owner; original geometry features',
        'quality_target':'Mean official IoU threshold credit; no added duration floor or short bonus',
        'model':params, 'neighbors':16, 'frame_weight':.01,
        'selection':'Baseline plus blend weights .5/1 and penalties .45/.55/.65, WPY spell priority, macro guard .002',
        'evaluation_scope':'Four training matches cannot evaluate this fitted head; WQQ reused complete-pipeline development only.',
        'source_sha256':sha256(__file__), 'graph_source_sha256':sha256(graph.__file__), 'lattice_source_sha256':sha256(lattice.__file__)})
    for key in graph.keys(TRAIN):
        raw=graph.signals(key); fold=0 if key.split('-')[0] in TRAIN[:2] else 1
        base=array('runs/two-hour-sprint/status-crossfit-v2/cost50',key,'predicted')
        learned=array(f'runs/two-hour-sprint/model/interp_learned_swap-{fold}',key)
        longer=array(f'runs/two-hour-sprint/model/long-{fold}',key)
        blended=logit(np.clip(.5*expit(learned)+.5*expit(longer),1e-8,1-1e-8))
        truth=graph.truth(key)
        for name,z in [('learned',learned),('blend',blended)]:
            x=raw.copy(); x[:,0]=z; seg=pool(x,base)
            f=graph.segment_features(x,seg); target,_=graph.quality_targets(truth,seg)
            assert np.isfinite(f).all()
            xx.append(f); yy.append(target); counts[key+'-'+name]={'proposals':len(seg),'mean_credit':float(target.mean())}
        print('matched quality features',key,'elapsed',round(time.monotonic()-started,1),flush=True)
    x=np.concatenate(xx); y=np.concatenate(yy); del xx,yy
    print('matched quality fit',x.shape,flush=True)
    model=HistGradientBoostingRegressor(**params).fit(x,y)
    with (out/'model.pkl').open('xb') as f: pickle.dump(model,f)
    write(out/'training.json',{'shape':list(x.shape),'counts':counts,'seconds':time.monotonic()-started,'input_sha256':HASHES,'reference_reads':sorted(READS)})
    return model

def prepared(out,key,model):
    dest=out/'cache';dest.mkdir(exist_ok=True); p=dest/(key+'.npz')
    if p.exists():
        with np.load(p) as a:return {k:a[k] for k in a.files}
    x,base=evidence(key);seg=pool(x,base); features=graph.segment_features(x,seg)
    result={'logit':x[:,0], 'base':base, 'segments':seg,
            'new_quality':np.clip(model.predict(features),0,1),
            'old_quality':np.clip(graph.get_model().predict(features),0,1)}
    np.savez_compressed(p,**result);return result

def predict(a,weight,penalty):
    q=weight*a['new_quality']+(1-weight)*a['old_quality']
    return graph.graph_decode(a['logit'],a['base'],a['segments'],q,penalty,.01)

def main():
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);a=p.parse_args()
    sys.addaudithook(guard);threadpool_limits(2)
    out=a.out.resolve();out.mkdir(parents=True,exist_ok=False)
    model=fit(out);pm=official_metrics();data={k:prepared(out,k,model) for k in graph.keys(['J03WPY'])}
    yy={k:graph.truth(k) for k in data};rows=[]
    for weight,penalty in [(0.,.55)]+[(w,p) for w in (.5,1.) for p in (.45,.55,.65)]:
        views={k:graph.metric(pm,yy[k],predict(v,weight,penalty)) for k,v in data.items()}
        row={'weight':weight,'penalty':penalty,'overall':{m:float(np.mean([v[m] for v in views.values()])) for m in ['spell','macro']},'views':views}
        rows.append(row);print('WPY',weight,penalty,row['overall'],flush=True)
    best=max((r for r in rows if r['overall']['macro']>=rows[0]['overall']['macro']-.002),key=lambda r:(r['overall']['spell'],r['overall']['macro']))
    write(out/'freeze.json',{'selected':best,'WPY_rows':rows,'model_sha256':sha256(out/'model.pkl'),'old_model_sha256':sha256(graph.RUN/'model.pkl'),'source_sha256':sha256(__file__),'WQQ_truth_read':False})
    dest=out/'predictions';dest.mkdir()
    for key in graph.keys(['J03WQQ']):
        values=prepared(out,key,model);pred=predict(values,best['weight'],best['penalty'])
        np.savez_compressed(dest/(key+'.npz'),predicted=pred,logit=values['logit'],status_mask=values['base'])
        print('matched quality predicted',key,flush=True)
    write(out/'inference.json',{'outputs':{p.name:sha256(p) for p in dest.glob('*.npz')},'input_sha256':HASHES,'reference_reads':sorted(READS),'WQQ_truth_read':False})

if __name__=='__main__':main()
